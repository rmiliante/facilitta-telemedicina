import type { PDFPage } from "pdf-lib";
import { rgb } from "pdf-lib";

/**
 * QR Code fixo que abre o validador oficial do governo (https://validar.iti.gov.br/).
 * É o mesmo em todos os documentos, por isso vai pronto (sem biblioteca):
 * cada linha é uma fileira de módulos, "1" = módulo escuro.
 */
const QR_ITI_ROWS = [
  "11111110000011000110001111111",
  "10000010100110110110001000001",
  "10111010100010101000101011101",
  "10111010000001110101001011101",
  "10111010001110000101001011101",
  "10000010001101110001101000001",
  "11111110101010101010101111111",
  "00000000001011110100100000000",
  "01110110000110110001000000110",
  "01110101101010000111001111001",
  "00000010101110100100101010110",
  "10001000001101101010000110001",
  "01111010100111100100010100111",
  "01001001001101010001001101111",
  "00110011101110011111011111011",
  "00010100001010000111111011000",
  "10101111111001111110000111001",
  "01010001111100101000100101100",
  "10010111101111011000001101000",
  "00011100001110000101111000111",
  "01001110011010101111111111100",
  "00000000110000100011100011011",
  "11111110011110100101101010110",
  "10000010100000111010100010000",
  "10111010011111110010111111101",
  "10111010100100001111000011010",
  "10111010111010111000100101101",
  "10000010101101101000101011010",
  "11111110000001111011101100010",
];

/** Desenha o QR com o canto inferior esquerdo em (x, y) e lado de `size` pontos. */
export function drawItiQr(page: PDFPage, x: number, y: number, size: number) {
  const n = QR_ITI_ROWS.length;
  const m = size / n;
  QR_ITI_ROWS.forEach((row, r) => {
    for (let c = 0; c < n; c++) {
      if (row[c] !== "1") continue;
      page.drawRectangle({
        x: x + c * m,
        y: y + size - (r + 1) * m,
        width: m + 0.05,
        height: m + 0.05,
        color: rgb(0, 0, 0),
      });
    }
  });
}
